#[test]
fn rejects_truncated_statement() {
    let doc = bytes("ISO-10303-21;\nHEADER;\nENDSEC;\nDATA;\n#1=IFCWALL('a')\nENDSEC;\n");
    assert_eq!(load(&doc), -17);
}

#[test]
fn rejects_documents_over_the_size_limit() {
    let mut doc = bytes("ISO-10303-21;\nHEADER;\nENDSEC;\nDATA;\n#1=IFCWALL('");
    doc.extend(std::iter::repeat_n(b'a', 33 * 1024 * 1024));
    doc.extend_from_slice(b"');\nENDSEC;\n");
    assert_eq!(load(&doc), -6);
}

#[test]
fn rejects_too_many_entities() {
    let mut doc = String::from("ISO-10303-21;\nHEADER;\nENDSEC;\nDATA;\n");
    for i in 1..=100_001u32 {
        doc.push_str(&format!("#{i}=IFCWALL($);\n"));
    }
    doc.push_str("ENDSEC;\n");
    assert_eq!(load(doc.as_bytes()), -7);
}

#[test]
fn rejects_excessive_nesting() {
    let mut doc = String::from("ISO-10303-21;\nHEADER;\nENDSEC;\nDATA;\n#1=IFCWALL(");
    for _ in 0..65 {
        doc.push('(');
    }
    for _ in 0..65 {
        doc.push(')');
    }
    doc.push_str(");\nENDSEC;\n");
    assert_eq!(load(doc.as_bytes()), -8);
}

// ---- Editing --------------------------------------------------------------

#[test]
fn every_editable_kind_can_be_updated() {
    let doc = bytes(concat!(
        "ISO-10303-21;\n",
        "HEADER;\n",
        "ENDSEC;\n",
        "DATA;\n",
        "#1=IFCWALL('name',42,.T.,#2,$,*);\n",
        "ENDSEC;\n",
    ));
    assert_eq!(load(&doc), 0);

    assert_eq!(ifc_update_attribute(0, 0, write_value("'new name'")), 0);
    assert_eq!(ifc_entity_attribute_kind(0, 0), 1);

    assert_eq!(ifc_update_attribute(0, 1, write_value("3.5")), 0);
    assert_eq!(ifc_entity_attribute_kind(0, 1), 2);

    assert_eq!(ifc_update_attribute(0, 2, write_value(".F.")), 0);
    assert_eq!(ifc_entity_attribute_kind(0, 2), 3);

    assert_eq!(ifc_update_attribute(0, 3, write_value("#9")), 0);
    assert_eq!(ifc_entity_attribute_kind(0, 3), 4);

    assert_eq!(ifc_update_attribute(0, 4, write_value("*")), 0);
    assert_eq!(ifc_entity_attribute_kind(0, 4), 5);

    assert_eq!(ifc_update_attribute(0, 5, write_value("$")), 0);
    assert_eq!(ifc_entity_attribute_kind(0, 5), 5);
}

#[test]
fn update_permits_switching_kind() {
    let doc = bytes("ISO-10303-21;\nHEADER;\nENDSEC;\nDATA;\n#1=IFCWALL(42);\nENDSEC;\n");
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_update_attribute(0, 0, write_value("'now a string'")), 0);
    assert_eq!(ifc_entity_attribute_kind(0, 0), 1);
}

#[test]
fn update_rejects_top_level_semicolon_and_comma() {
    let doc = bytes("ISO-10303-21;\nHEADER;\nENDSEC;\nDATA;\n#1=IFCWALL(42);\nENDSEC;\n");
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_update_attribute(0, 0, write_value("1;DROP")), -5);
    assert_eq!(ifc_update_attribute(0, 0, write_value("1,2")), -5);
}

#[test]
fn failed_update_rolls_back_to_the_previous_document() {
    let doc = bytes("ISO-10303-21;\nHEADER;\nENDSEC;\nDATA;\n#1=IFCWALL(42);\nENDSEC;\n");
    assert_eq!(load(&doc), 0);
    assert_eq!(
        ifc_update_attribute(0, 0, write_value("'unterminated)")),
        -5
    );
    let len = ifc_serialize();
    assert_eq!(read_output(len as usize), doc);
    assert_eq!(ifc_entity_attribute_kind(0, 0), 2);
}

#[test]
fn find_entity_locates_by_id() {
    let doc = bytes(concat!(
        "ISO-10303-21;\n",
        "HEADER;\n",
        "ENDSEC;\n",
        "DATA;\n",
        "#5=IFCWALL($);\n",
        "#7=IFCWALL($);\n",
        "ENDSEC;\n",
    ));
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_find_entity(7), 1);
    assert_eq!(ifc_find_entity(5), 0);
    assert_eq!(ifc_find_entity(999), -3);
}

#[test]
fn last_error_reflects_the_most_recent_failure() {
    let doc = bytes("HEADER;\n");
    assert_eq!(load(&doc), -9);
    assert_eq!(ifc_last_error(), 9);
}

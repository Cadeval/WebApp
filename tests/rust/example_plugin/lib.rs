use super::*;

fn bytes(source: &str) -> Vec<u8> {
    source.as_bytes().to_vec()
}

fn minimal_document() -> Vec<u8> {
    bytes(concat!(
        "ISO-10303-21;\n",
        "HEADER;\n",
        "FILE_DESCRIPTION((''),'2;1');\n",
        "ENDSEC;\n",
        "DATA;\n",
        "ENDSEC;\n",
        "END-ISO-10303-21;\n",
    ))
}

// ---- Loading a fresh document through the ABI -------------------------

fn load(doc: &[u8]) -> i32 {
    let ptr = ifc_input_reserve(doc.len() as u32);
    if ptr == usize::MAX {
        return STATE.with(|state| -state.borrow().last_error);
    }
    unsafe {
        std::ptr::copy_nonoverlapping(doc.as_ptr(), ptr as *mut u8, doc.len());
    }
    ifc_load(doc.len() as u32)
}

fn write_value(value: &str) -> u32 {
    let bytes = value.as_bytes();
    let ptr = ifc_input_reserve(bytes.len() as u32);
    unsafe {
        std::ptr::copy_nonoverlapping(bytes.as_ptr(), ptr as *mut u8, bytes.len());
    }
    bytes.len() as u32
}

fn read_output(len: usize) -> Vec<u8> {
    let ptr = ifc_output_ptr();
    let mut buffer = vec![0u8; len];
    unsafe {
        std::ptr::copy_nonoverlapping(ptr as *const u8, buffer.as_mut_ptr(), len);
    }
    buffer
}

#[test]
fn parses_a_minimal_valid_document() {
    let doc = minimal_document();
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_entity_count(), 0);
}

#[test]
fn oversized_reservation_is_rejected_before_allocation_and_preserves_state() {
    let doc = minimal_document();
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_input_reserve(u32::MAX), usize::MAX);
    STATE.with(|state| {
        let state = state.borrow();
        assert_eq!(state.input, doc);
        assert_eq!(state.last_error, ErrorCode::TooLarge.code());
    });
    let len = ifc_serialize();
    assert_eq!(read_output(len as usize), doc);
}

#[test]
fn parses_typical_header_metadata_without_indexing_it() {
    let doc = bytes(concat!(
        "ISO-10303-21;\n",
        "HEADER;\n",
        "FILE_DESCRIPTION((''),'2;1');\n",
        "FILE_NAME('demo.ifc','2024-01-01',('author'),('org'),'app','app','');\n",
        "FILE_SCHEMA(('IFC4'));\n",
        "ENDSEC;\n",
        "DATA;\n",
        "#1=IFCPROJECT('guid',$,'Demo',$,$,$,$,$,$);\n",
        "ENDSEC;\n",
        "END-ISO-10303-21;\n",
    ));
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_entity_count(), 1);
}

#[test]
fn indexes_every_editable_attribute_kind() {
    let doc = bytes(concat!(
        "ISO-10303-21;\n",
        "HEADER;\n",
        "ENDSEC;\n",
        "DATA;\n",
        "#1=IFCWALL('name',42,.T.,#2,$,*);\n",
        "ENDSEC;\n",
    ));
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_entity_count(), 1);
    assert_eq!(ifc_entity_id(0), 1);
    assert_eq!(ifc_entity_attribute_count(0), 6);
    assert_eq!(ifc_entity_attribute_kind(0, 0), 1); // quoted string
    assert_eq!(ifc_entity_attribute_kind(0, 1), 2); // number
    assert_eq!(ifc_entity_attribute_kind(0, 2), 3); // enum/logical
    assert_eq!(ifc_entity_attribute_kind(0, 3), 4); // reference
    assert_eq!(ifc_entity_attribute_kind(0, 4), 5); // $
    assert_eq!(ifc_entity_attribute_kind(0, 5), 5); // *
}

#[test]
fn lists_and_wrapped_values_are_visible_but_read_only() {
    let doc = bytes(concat!(
        "ISO-10303-21;\n",
        "HEADER;\n",
        "ENDSEC;\n",
        "DATA;\n",
        "#1=IFCWALL((1,2,3),IFCLABEL('x'));\n",
        "ENDSEC;\n",
    ));
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_entity_attribute_kind(0, 0), 0);
    assert_eq!(ifc_entity_attribute_kind(0, 1), 0);
    assert_eq!(ifc_update_attribute(0, 0, write_value("$")), -4); // read-only
}

// ---- Byte-for-byte fidelity --------------------------------------------

#[test]
fn serialize_without_edits_is_byte_identical() {
    let doc = minimal_document();
    assert_eq!(load(&doc), 0);
    let len = ifc_serialize();
    assert!(len >= 0);
    assert_eq!(read_output(len as usize), doc);
}

#[test]
fn escaped_apostrophes_round_trip_inside_strings() {
    let doc = bytes(concat!(
        "ISO-10303-21;\n",
        "HEADER;\n",
        "ENDSEC;\n",
        "DATA;\n",
        "#1=IFCWALL('it''s a wall');\n",
        "ENDSEC;\n",
    ));
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_entity_attribute_kind(0, 0), 1);
    let len = ifc_entity_attribute(0, 0);
    assert_eq!(read_output(len as usize), bytes("'it''s a wall'"));
}

#[test]
fn multiline_entities_comments_and_crlf_are_supported() {
    let doc = bytes(concat!(
        "ISO-10303-21;\r\n",
        "/* generated by test */\r\n",
        "HEADER;\r\n",
        "ENDSEC;\r\n",
        "DATA;\r\n",
        "#1=IFCWALL(\r\n",
        "  'multi',\r\n",
        "  /* a comment inside the call */\r\n",
        "  42\r\n",
        ");\r\n",
        "ENDSEC;\r\n",
    ));
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_entity_count(), 1);
    assert_eq!(ifc_entity_attribute_count(0), 2);
    let len = ifc_serialize();
    assert_eq!(read_output(len as usize), doc);
}

#[test]
fn empty_data_section_has_no_entities() {
    let doc = minimal_document();
    assert_eq!(load(&doc), 0);
    assert_eq!(ifc_entity_count(), 0);
    assert_eq!(ifc_find_entity(1), -3); // not found
}

